# =====================================================================
# Текстовая игра-новелла "Город, который забыл тебя"
# Автор: Корепанова Мария, группа ПО-11/1-26
# Ты просыпаешься в городе, где никто тебя не узнаёт. Даже документы
# утверждают, что тебя никогда не существовало.
# Уровень 1 - расследование: улики, разговоры с жителями, своё имя
# Уровень 2 - мэрия: стиратели памяти и разговор со Смотрителем
# =====================================================================

import random

# словарь - игрок и его характеристики
player = {"имя": "???", "рассудок": 3}

# список - инвентарь (улики)
inventory = []

# множество - восстановленные воспоминания (без повторов)
memories = set()

# словарь - предмет и его описание
items = {
    "газета": "Сегодняшняя газета. Заголовок: 'В городе никто не пропадал'.",
    "ключ": "Маленький ключ с биркой 'Почта, ящик 12'.",
    "письмо": "Конверт: 'А. Воронову, ул. Липовая, 7, кв. 12'.",
    "фотография": "Ты и девушка у фонтана. На обороте: 'Лёше от Ани'.",
    "чек": "Чек из кафе 'Ворона': раф каждое утро в 8:15.",
    "справка": "Временная справка о личности.",
    "зеркало": "Осколок зеркала. Стиратели боятся своего отражения.",
    "пропуск": "Пропуск в кабинет Смотрителя. Подписан: 'Анна К.'",
}

# кортеж - команды игры (неизменяемые)
commands = ("осмотреться", "идти", "взять", "изучить", "говорить",
            "улики", "воспоминания", "помощь", "выход")

game_over = False    # True - игрок проиграл или вышел
level1_done = False
level2_done = False

print("==========================================================")
print("            ГОРОД, КОТОРЫЙ ЗАБЫЛ ТЕБЯ")
print("==========================================================")

# ====================================================================
# УРОВЕНЬ 1: Чужие улицы
# ====================================================================

print("\nУРОВЕНЬ 1: Чужие улицы")
print("Ты просыпаешься в незнакомой квартире. В паспорте - пустые")
print("страницы. Хозяйка кричит, что квартира год стоит пустой.")
print("Найди доказательства и узнай, кто ты. ('помощь' - команды)")

# словари для мест: описание, предметы (списки), выходы (списки), жители
descriptions = {
    "квартира": "Пыльная комната. На тумбочке что-то блестит.",
    "улица": "Серая улица. Прохожие смотрят сквозь тебя.",
    "кафе": "Кафе 'Ворона'. Пахнет кофе и чем-то родным.",
    "почта": "Ряды почтовых ящиков. Ящик 12 заперт.",
    "парк": "Старый фонтан. Под скамейкой что-то лежит.",
    "паспортный стол": "Окошко и строгая сотрудница.",
}
place_items = {
    "квартира": ["ключ"],
    "улица": ["газета"],
    "кафе": ["чек"],
    "почта": [],
    "парк": ["фотография"],
    "паспортный стол": [],
}
exits = {
    "квартира": ["улица"],
    "улица": ["квартира", "кафе", "почта", "парк", "паспортный стол"],
    "кафе": ["улица"],
    "почта": ["улица"],
    "парк": ["улица"],
    "паспортный стол": ["улица"],
}
people = {
    "квартира": "хозяйка",
    "кафе": "бариста",
    "почта": "почтальон",
    "парк": "старик",
}

# словарь - что житель говорит при встрече
hello = {
    "хозяйка": "Как вы сюда попали?! Я вас первый раз вижу!",
    "бариста": "Добрый день! Простите, мы знакомы?",
    "почтальон": "Ящик 12? Он числится пустым уже год.",
    "старик": "Садись, сынок. Все мы тут кого-то забыли.",
}

# словарь - житель: (нужная улика, ответ, воспоминание, подарок)
clues = {
    "хозяйка": ("письмо", "Липовая, 7, кв. 12... Это же эта квартира!",
                "Я жил на улице Липовой", ""),
    "бариста": ("чек", "Раф в 8:15! Вы брали его каждое утро! Вы - Лёша!",
                "Меня зовут Лёша (Алексей)", ""),
    "почтальон": ("ключ", "Ключ от 12-го? Держите письмо. Воронову... я помню его!",
                  "Моя фамилия - Воронов", "письмо"),
    "старик": ("фотография", "Это Анечка! Она работает в архиве мэрии.",
               "Аня - мой близкий человек", ""),
}

need_proofs = {"письмо", "фотография"}   # множество нужных доказательств
visited = {"квартира"}                   # множество посещённых мест
current = "квартира"

while not level1_done and not game_over:
    text = input("\n> ").strip().lower()
    parts = text.split(" ")
    command = parts[0]
    arg = " ".join(parts[1:])

    if command not in commands:
        print("Непонятная команда. Введи 'помощь'.")

    elif command == "помощь":
        print("Команды: осмотреться, идти <место>, взять <предмет>,")
        print("изучить <предмет>, говорить <житель>, улики, воспоминания, выход")

    elif command == "выход":
        game_over = True

    elif command == "улики":
        print("Улики:", ", ".join(inventory))
        print("Рассудок:", player["рассудок"])

    elif command == "воспоминания":
        for m in memories:
            print(" -", m)

    elif command == "изучить":
        if arg in inventory:
            print(items[arg])
        else:
            print("У тебя нет такой вещи.")

    elif command == "осмотреться":
        print(descriptions[current])
        print("Предметы:", ", ".join(place_items[current]))
        if current in people:
            print("Здесь есть:", people[current])
        print("Можно пойти:", ", ".join(exits[current]))

    elif command == "взять":
        if arg in place_items[current]:
            place_items[current].remove(arg)
            inventory.append(arg)
            print("Ты забираешь:", arg)
        else:
            print("Здесь этого нет.")

    elif command == "говорить":
        if current in people and people[current] == arg:
            print(f'{arg.capitalize()}: "{hello[arg]}"')
            item = input("Какую улику показать? (Enter - никакую) ").strip().lower()
            need_item, answer, memory, gift = clues[arg]
            if item == "":
                print("Ты молча отходишь.")
            elif item not in inventory:
                print("У тебя нет такой улики.")
            elif item == need_item:
                print(f'{arg.capitalize()}: "{answer}"')
                if memory not in memories:
                    memories.add(memory)
                    print("* Новое воспоминание:", memory)
                if gift != "" and gift not in inventory:
                    inventory.append(gift)
                    print("* Тебе дали:", gift)
            else:
                print(f'{arg.capitalize()}: "Впервые это вижу."')
        else:
            print("Здесь нет такого человека.")

    elif command == "идти":
        if arg in exits[current]:
            current = arg
            visited.add(current)
            print(f"[{current.upper()}]")
            print(descriptions[current])

            if current == "паспортный стол":
                if need_proofs.issubset(set(inventory)):
                    print('Сотрудница: "Доказательства есть. Назовите полное имя."')
                    name = input("Имя и фамилия: ").strip().lower()
                    if "алексей" in name and "воронов" in name:
                        player["имя"] = "Алексей Воронов"
                        inventory.append("справка")
                        print('Сотрудница: "Алексей Воронов... Нашла! Запись стёрта,')
                        print('но вот справка. Остальное знают только в мэрии."')
                        print("Мест осмотрено:", len(visited), "из", len(descriptions))
                        level1_done = True
                    else:
                        print('Сотрудница: "Такого человека нет в базе."')
                        player["рассудок"] -= 1
                        print("Голова кружится... Рассудок:", player["рассудок"])
                else:
                    print('Сотрудница: "Без доказательств ничего не выдам."')
                    print("Не хватает:", ", ".join(need_proofs - set(inventory)))
        else:
            print("Туда отсюда не попасть.")

    if player["рассудок"] == 0:
        game_over = True

# ====================================================================
# УРОВЕНЬ 2: Мэрия
# ====================================================================

if level1_done:
    print("\n*** Уровень 1 пройден! ***")
    print("\nУРОВЕНЬ 2: Мэрия")
    print(f"Теперь ты знаешь имя - {player['имя']}. Но в базе города тебя")
    print("всё ещё нет. Ответы в мэрии, у таинственного Смотрителя.")

    descriptions = {
        "холл": "Мраморный холл. Часы идут назад. На полу блестит осколок.",
        "лестница": "Узкая лестница наверх. Пахнет пылью и забвением.",
        "архив": "Бесконечные полки с папками. За столом - девушка.",
        "кабинет": "Пустой кабинет. В кресле - человек без лица.",
    }
    place_items = {"холл": ["зеркало"], "лестница": [], "архив": [], "кабинет": []}
    exits = {
        "холл": ["лестница", "архив"],
        "лестница": ["холл", "кабинет"],
        "архив": ["холл"],
        "кабинет": ["лестница"],
    }

    # список противников; словари - где стоят и чем их победить
    enemies = ["охранник", "серый человек"]
    enemy_place = {"архив": "охранник", "лестница": "серый человек"}
    weakness = {"охранник": "справка", "серый человек": "зеркало"}
    defeated = set()

    current = "холл"
    print(f"[{current.upper()}]")
    print(descriptions[current])

while level1_done and not level2_done and not game_over:
    text = input("\n> ").strip().lower()
    parts = text.split(" ")
    command = parts[0]
    arg = " ".join(parts[1:])

    if command not in commands:
        print("Непонятная команда. Введи 'помощь'.")

    elif command == "помощь":
        print("Команды: осмотреться, идти <место>, взять <предмет>,")
        print("изучить <предмет>, говорить <житель>, улики, воспоминания, выход")

    elif command == "выход":
        game_over = True

    elif command == "улики":
        print("Улики:", ", ".join(inventory))
        print("Рассудок:", player["рассудок"])

    elif command == "воспоминания":
        for m in memories:
            print(" -", m)

    elif command == "изучить":
        if arg in inventory:
            print(items[arg])
        else:
            print("У тебя нет такой вещи.")

    elif command == "осмотреться":
        print(descriptions[current])
        print("Предметы:", ", ".join(place_items[current]))
        print("Можно пойти:", ", ".join(exits[current]))

    elif command == "взять":
        if arg in place_items[current]:
            place_items[current].remove(arg)
            inventory.append(arg)
            print("Ты забираешь:", arg)
        else:
            print("Здесь этого нет.")

    elif command == "говорить":
        if current == "архив" and arg == "аня":
            print('Аня: "Архив закрыт... Почему мне хочется плакать?"')
            item = input("Какую улику показать? ").strip().lower()
            if item == "фотография" and item in inventory:
                print('Аня: "Лёша?.. Лёша! Я вспомнила! Тебя стёрли!')
                print('Вот пропуск к Смотрителю, иди!"')
                memories.add("Аня ждала меня всё это время")
                if "пропуск" not in inventory:
                    inventory.append("пропуск")
                print("* Тебе дали: пропуск")
            else:
                print('Аня: "Нет... не помню."')
        else:
            print("Здесь нет такого человека.")

    elif command == "идти":
        if arg not in exits[current]:
            print("Туда отсюда не попасть.")
        elif arg == "кабинет" and "пропуск" not in inventory:
            print("Дверь заперта. Нужен пропуск.")
        else:
            can_go = True

            # встреча со стирателем
            if arg in enemy_place and enemy_place[arg] not in defeated:
                enemy = enemy_place[arg]
                print(f"\nДорогу преграждает {enemy}!")
                print("Варианты: показать <улика>, бежать, улики")
                fight_over = False
                while not fight_over and not game_over:
                    words = input("встреча> ").strip().lower().split(" ")
                    action = words[0]
                    thing = " ".join(words[1:])
                    if action == "улики":
                        print("Улики:", ", ".join(inventory))
                    elif action == "показать":
                        if thing in inventory and thing == weakness[enemy]:
                            print(f"Ты показываешь {thing}. {enemy.capitalize()} отступает!")
                            defeated.add(enemy)
                            print("Стирателей обойдено:", len(defeated), "из", len(enemies))
                            fight_over = True
                        else:
                            print(f"{enemy.capitalize()} лишь усмехается.")
                            player["рассудок"] -= 1
                            print("Мысли путаются... Рассудок:", player["рассудок"])
                    elif action == "бежать":
                        if random.randint(1, 2) == 1:
                            print("Ты успеваешь скрыться за углом.")
                            can_go = False
                            fight_over = True
                        else:
                            print("Тебя хватают за плечо!")
                            player["рассудок"] -= 1
                            print("Мысли путаются... Рассудок:", player["рассудок"])
                    else:
                        print("Нет времени на это!")
                    if player["рассудок"] == 0:
                        game_over = True

            if can_go and not game_over:
                current = arg
                print(f"[{current.upper()}]")
                print(descriptions[current])

                # финал: вопросы Смотрителя
                if current == "кабинет":
                    print('\nСмотритель: "Я стёр тебя, потому что ты сам попросил.')
                    print('Хочешь вернуться? Докажи, что помнишь свою жизнь."')
                    # словарь - вопрос: кортеж правильных ответов
                    questions = {
                        "Как зовут девушку с фотографии?": ("аня", "анна"),
                        "На какой улице ты жил?": ("липовая", "липовой"),
                        "В каком кафе ты пил кофе каждое утро?": ("ворона",),
                    }
                    answered = set()
                    for q in questions:
                        while q not in answered and not game_over:
                            reply = input(f"\n{q}\n> ").strip().lower()
                            if reply in questions[q]:
                                answered.add(q)
                                print("Город на миг вспыхивает.", len(answered), "/", len(questions))
                            else:
                                print('Смотритель: "Ты забываешь..."')
                                player["рассудок"] -= 1
                                print("Рассудок:", player["рассудок"])
                                if player["рассудок"] == 0:
                                    game_over = True
                    if len(answered) == len(questions):
                        level2_done = True

    if player["рассудок"] == 0:
        game_over = True

# ====================================================================
# Конец игры
# ====================================================================

if level2_done:
    print("\n*** Уровень 2 пройден! ***")
    print("\n==========================================================")
    print("                    ТЫ ВЕРНУЛСЯ")
    print("==========================================================")
    print(f"{player['имя']} снова существует. Хозяйка здоровается,")
    print("бариста уже готовит раф, а у фонтана тебя ждёт Аня.")
    print("Восстановленные воспоминания:")
    for m in memories:
        print(" -", m)
else:
    print("\n==========================================================")
    print("                       КОНЕЦ")
    print("==========================================================")
    print("Ты растворяешься в тумане. Город так и не вспомнил тебя.")
